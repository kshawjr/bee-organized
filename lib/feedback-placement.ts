// lib/feedback-placement.ts
//
// "Where does this report probably live?" — matching an owner's own words
// against docs/screen-map.json. Issue 248 step 2.
//
// ─── THE PREMISE THIS CORRECTS ────────────────────────────────────────
// The issue-247 scout judged that 25 of 28 open reports carried too little to
// locate, and cited TITLES as evidence: "Quo", "Guide", "Toggle Button",
// "bigger font for us tenured bees". That measurement was taken from titles and
// character counts. It was wrong, and the direction of the error matters: the
// titles are the thin part. Measured over the same 28 rows, the DESCRIPTIONS
// average 147 characters and only 5 fall under 40. "Quo" is a 253-character
// integration request naming a phone system and a business number.
//
// So this matcher reads the DESCRIPTION first and the title second. Title text
// is scored at TITLE_WEIGHT — it can break a tie, it cannot carry a placement.
// A title like "Problem with Engagement – Aug 2026" (autogenerated by the
// composer) must never be what places an item.
//
// ─── WHY `says` IS THE FIELD WE MATCH ─────────────────────────────────
// The map carries `says` — "how a non-technical person refers to this surface"
// — precisely for this. `surface` is written in our words; `says` is written in
// theirs, which is the vocabulary the reports actually arrive in. So `says`
// phrases score highest, `surface` contributes at a lower weight, and `nav` is
// ignored entirely (it is a one-word bucket name shared by dozens of entries —
// pure noise at this granularity).
//
// ─── WHY IDF, AND NOT A KEYWORD LIST ──────────────────────────────────
// A hand-written keyword list is a second map that rots independently of the
// first. Instead every token is weighted by how RARE it is across the 119
// entries' vocabulary. "client", "email" and "the" appear in dozens of entries
// and are therefore nearly worthless as evidence; "snooze", "thumbtack",
// "kanban" and "unsubscribe" appear in one or two and are decisive. This is
// what stops a description full of ordinary business words from lighting up
// forty entries at once with false confidence.
//
// ─── THE HONESTY RULE IS THE OUTPUT TYPE ──────────────────────────────
// A confident wrong pointer is worse than silence: it sends the reader to the
// wrong file and they trust it, because it was stated with confidence. So
// "cannot place this" is a first-class result, not a failure path — the
// function returns one of three shapes and the caller cannot get a file path
// out of the unplaced one. Ambiguity is reported AS ambiguity (a shortlist),
// never collapsed to a winner by rounding.

export interface ScreenMapEntry {
  id: string
  surface: string
  nav?: string
  file: string
  symbol?: string
  lines?: number[]
  says?: string[]
  note?: string
}

export type PlacementConfidence = 'confident' | 'possible' | 'none'

export interface PlacementCandidate {
  id: string
  surface: string
  file: string
  lines?: number[]
  score: number
  /** The owner's own words that matched — why this candidate is here at all. */
  matched: string[]
  /**
   * The weight of the RAREST word that matched. This is the number that says
   * whether the match rests on a word that names something ("guide", in 3 of
   * 120 entries) or on one that merely appears everywhere ("client", in 19).
   * Kevin described exactly this distinction in plain English when he called
   * `clients, client` noise and `guide` real — so the renderer reads it.
   */
  peak: number
}

export interface Placement {
  confidence: PlacementConfidence
  candidates: PlacementCandidate[]
}

// ─── Words that must not be allowed to place anything ─────────────────
//
// IDF alone is not sufficient, and the first run over the real 28 proved it.
// IDF measures rarity WITHIN THE MAP, and rare-in-the-map is not the same as
// informative. "over", "behind", "make" and "many" each appear in one or two
// entries' phrasing, so IDF hands them near-maximum weight — and then a
// description containing "a new lead over the weekend" gets pulled toward
// whichever entry happened to use the word "over". Two classes of word have to
// be removed by name.

