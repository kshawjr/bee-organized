// 2. The product's own name, and the vocabulary of reporting itself.
//
// THIS IS THE ONE THAT CAUSED REAL DAMAGE. "bee" and "hub" appear in the map
// (shell.ask-bee-hub's `says` is "ask bee hub"), are rare there, and therefore
// scored as decisive evidence. But every owner writes "Bee Hub" when describing
// anything at all — so the Thumbtack integration request and the Quo phone
// request were both placed CONFIDENTLY on the help panel, on the strength of
// the product's own name. That is precisely the confident-wrong-pointer this
// design exists to prevent.
//
// The same holds for "feedback", "problem", "issue" and "report": every row in
// this table is a report of a problem. A word that is present by construction
// is evidence of nothing.
const AMBIENT_WORDS = [
  'bee', 'bees', 'beehub', 'hub', 'crm', 'app', 'system', 'platform',
  'feedback', 'report', 'reported', 'problem', 'problems', 'issue', 'issues',
  'bug', 'broken', 'work', 'working', 'works',
]

const STOPWORDS = new Set([...GENERIC_WORDS, ...AMBIENT_WORDS])

// Apostrophes are DROPPED rather than kept, so "isn't" and "isnt" are one
// token. Keeping them made every contraction its own rare word — the map's
// phrasing ("a client isn't in the list", "the invite didn't arrive") gave
// "isn't" and "didn't" near-maximum IDF, and they turned up as evidence in the
// first run's matches. Contractions are grammar; they are stopworded below.
export function normalizeText(text: string): string {
  return String(text || '')
    .toLowerCase()
    .replace(/[‘’]/g, "'")
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

export function tokenize(text: string): string[] {
  return normalizeText(text)
    .split(' ')
    .filter(t => t.length > 2 && !STOPWORDS.has(t))
}

// ─── Tuning ───────────────────────────────────────────────────────────
// Every threshold here was set by running the matcher over the 28 real open
// items and reading the output, not by taste. They are deliberately
// conservative: the failure this design fears is a confident wrong pointer, so
// where a threshold was arguable it was set to demote rather than promote.

/** Title tokens count for this fraction of a description token. Title is a tie-breaker. */
const TITLE_WEIGHT = 0.35
/** A whole `says` phrase found verbatim in the text — the strongest signal available. */
const PHRASE_BONUS = 2.2
/** `surface` is our wording, not theirs. Present, but secondary to `says`. */
const SURFACE_WEIGHT = 0.45
/** Below this, nothing is worth showing at all. */
const FLOOR = 1.4
/**
 * A shortlist is only offered if its leader clears this. Below it, say nothing.
 *
 * THE LIMIT OF A LEXICAL MATCHER, STATED HONESTLY. There is no threshold that
 * separates a good single-word match from a bad one, and the real data proves
 * it: "notes" (from "really want notes to come over" → the notes box) and
 * "feed" (from "leads feed directly into Jobber" → the activity feed) both
 * occur in exactly one map entry, so both carry identical, maximum weight. One
 * is right and one is a verb that collided with a noun. No amount of tuning
 * tells them apart.
 *
 * So single weak candidates are kept rather than guessed at OR silently
 * dropped, and the defence is moved into the rendering: every candidate is
 * printed with the words that matched it. "possible — the notes box (matched:
 * feed)" is self-auditing in about one second of reading, which a bare file
 * path would not be.
 */
const POSSIBLE_MIN = 2.2
/** At or above this, AND corroborated, AND clear of the runner-up, one surface is named. */
const CONFIDENT_MIN = 3.2
/**
 * Top must DOMINATE the runner-up — not merely lead it — to be stated as one
 * answer rather than a shortlist.
 *
 * Set from the observed separation on the 28 real items, where the two correct
 * confident placements cleared the field by 2.36× and 2.45×, and the two wrong
 * ones (an automated-email complaint pulled onto Settings→Location by the word
 * "business"; a push-to-Jobber request pulled onto Settings→Profile by
 * "booking") both sat at exactly 1.73×. Word-sense collisions like those two
 * cannot be resolved lexically — "recent business" and "my business details"
 * are the same token — so the defence is to refuse to name one file unless
 * nothing else is close. Both now degrade to shortlists, which is the honest
 * reading of the evidence rather than a failure.
 *
 * Four data points is thin, and this threshold should be revisited as the
 * queue grows. It is deliberately set to under-claim: the cost of a demoted
 * good placement is a shortlist Kevin skims, and the cost of a promoted bad
 * one is a wasted morning in the wrong file.
 */
const CONFIDENT_MARGIN = 2.0
/**
 * A token this rare is DISTINCTIVE — it names a thing rather than describes one.
 * At 119 entries: df=1 → 4.08, df=2 → 3.68, df=5 → 2.99, df=10 → 2.38.
 * "notifications", "kanban", "unsubscribe" clear it; "email", "client", "list" do not.
 */
export const DISTINCTIVE_MIN = 3.0
/** A shortlist keeps candidates within this fraction of the leader. */
const SHORTLIST_BAND = 0.55
const SHORTLIST_MAX = 3

interface EntryIndex {
  entry: ScreenMapEntry
  /** token -> weight contributed if the description contains it */
  tokens: Map<string, number>
  /** multi-word `says` phrases, normalized, for verbatim substring hits */
  phrases: string[]
  /** Breadth penalty — see buildPlacementIndex. */
  norm: number
}

export interface PlacementIndex {
  entries: EntryIndex[]
  idf: Map<string, number>
}

// Build once per run, not once per item — 28 items × 119 entries otherwise
// re-derives the same vocabulary 28 times.
export function buildPlacementIndex(entries: ScreenMapEntry[]): PlacementIndex {
  const docFreq = new Map<string, number>()
  const prepared = entries.map(entry => {
    const saysTokens = new Set<string>()
    const phrases: string[] = []
    for (const phrase of entry.says || []) {
      const norm = normalizeText(phrase)
      if (norm.split(' ').filter(w => !STOPWORDS.has(w)).length >= 2) phrases.push(norm)
      tokenize(phrase).forEach(t => saysTokens.add(t))
    }
    const surfaceTokens = new Set(tokenize(entry.surface))
    const all = new Set<string>()
    saysTokens.forEach(t => all.add(t))
    surfaceTokens.forEach(t => all.add(t))
    all.forEach(t => docFreq.set(t, (docFreq.get(t) || 0) + 1))
    return { entry, saysTokens, surfaceTokens, phrases }
  })

  const n = Math.max(1, prepared.length)
  const idf = new Map<string, number>()
  docFreq.forEach((df, token) => {
    // Standard smoothed IDF, floored at 0. A token in >half the entries lands
    // at ~0 and is thereby unable to place anything on its own.
    idf.set(token, Math.max(0, Math.log(n / (1 + df))))
  })

  const withTokens = prepared.map(p => {
    const tokens = new Map<string, number>()
    p.saysTokens.forEach(t => tokens.set(t, idf.get(t) || 0))
    p.surfaceTokens.forEach(t => {
      const w = (idf.get(t) || 0) * SURFACE_WEIGHT
      tokens.set(t, Math.max(tokens.get(t) || 0, w))
    })
    let mass = 0
    tokens.forEach(w => { mass += w })
    return { ...p, tokens, mass }
  })

  // ─── The breadth penalty ────────────────────────────────────────────
  // Entries are not equally sized. settings.location is a grab-bag ("my
  // business details", "the address on my emails", "the reply-to address", "my
  // company info", "the review link"); clients.close-won is four tight
  // phrases. Without a correction the grab-bag wins on surface area alone: on
  // the first real run, "a client forward an email ... offering a discount for
  // a google review" was placed CONFIDENTLY on settings.location, because
  // "business" + "review" + "email" happened to co-occur in its vocabulary.
  // Three ordinary words, three different meanings, one wrong file.
  //
  // Dividing by sqrt(mass / medianMass) makes the score "how much of THIS
  // entry's vocabulary did we hit", not "how many words did we hit at all". A
  // broad entry must be matched broadly to win. Median rather than mean so a
  // couple of very large entries don't drag the baseline.
  const masses = withTokens.map(p => p.mass).sort((a, b) => a - b)
  const median = masses[Math.floor(masses.length / 2)] || 1

  const indexed: EntryIndex[] = withTokens.map(p => ({
    entry: p.entry,
    tokens: p.tokens,
    phrases: p.phrases,
    norm: Math.max(0.6, Math.sqrt(Math.max(p.mass, 0.001) / median)),
  }))

  return { entries: indexed, idf }
}

function scoreEntry(
  indexed: EntryIndex,
  descTokens: Set<string>,
  titleTokens: Set<string>,
  descNorm: string,
): { score: number; matched: string[]; peak: number; phraseHit: boolean; hits: number } {
  let score = 0
  let peak = 0
  let hits = 0
  let phraseHit = false
  const matched: string[] = []

  indexed.tokens.forEach((weight, token) => {
    if (weight <= 0) return
    if (descTokens.has(token)) {
      score += weight
      peak = Math.max(peak, weight)
      hits++
      matched.push(token)
    } else if (titleTokens.has(token)) {
      score += weight * TITLE_WEIGHT
      hits++
      matched.push(token)
    }
  })

  // A whole phrase in the owner's vocabulary, verbatim. Scaled by the phrase's
  // own rarity so "the menu" cannot outweigh "snooze not available".
  for (const phrase of indexed.phrases) {
    if (!descNorm.includes(phrase)) continue
    const rarity = tokenize(phrase).reduce((s, t) => s + (indexed.tokens.get(t) || 0), 0)
    score += PHRASE_BONUS * Math.min(1, rarity / 2)
    if (rarity >= DISTINCTIVE_MIN) phraseHit = true
    matched.push(phrase)
  }

  return { score: score / indexed.norm, matched, peak, phraseHit, hits }
}

/**
 * Where does this report probably live?
 *
 * Reads `description` first; `title` only supplements it. Returns
 * confidence:'none' with no candidates whenever the evidence does not support
 * naming a file — that is a real answer, and the caller must print it as one.
 */
export function rankPlacements(
  item: { title?: string | null; description?: string | null },
  index: PlacementIndex,
): (PlacementCandidate & { corroborated: boolean })[] {
  const descNorm = normalizeText(item.description || '')
  const descTokens = new Set(tokenize(item.description || ''))
  const titleTokens = new Set(tokenize(item.title || ''))

  if (descTokens.size === 0 && titleTokens.size === 0) return []

  const scored: (PlacementCandidate & { corroborated: boolean })[] = []
  for (const indexed of index.entries) {
    const { score, matched, peak, phraseHit, hits } = scoreEntry(
      indexed, descTokens, titleTokens, descNorm,
    )
    if (score < FLOOR) continue
    // ─── The padding gate ───────────────────────────────────────────
    // A candidate must rest on TWO independent words from the description, or
    // on ONE distinctive enough to name a thing. Without this, entries sail
    // into shortlists on a single ordinary word: the Thumbtack request was
    // being offered three candidates whose entire evidence was the word "all",
    // and the Snooze request three whose evidence was "section". A shortlist
    // assembled from noise is padding, and padding is what teaches the reader
    // to stop reading. Better to return nothing and say so.
    if (hits < 2 && peak < DISTINCTIVE_MIN) continue
    scored.push({
      id: indexed.entry.id,
      surface: indexed.entry.surface,
      file: indexed.entry.file,
      lines: indexed.entry.lines,
      score: Math.round(score * 100) / 100,
      // Longest first: the phrase that matched is more informative than the
      // single tokens inside it.
      matched: Array.from(new Set(matched)).sort((a, b) => b.length - a.length).slice(0, 4),
      peak: Math.round(peak * 100) / 100,
      // ─── What "confident" has to be earned by ───────────────────────
      // Not accumulated score. Score accumulates from ordinary words, and
      // ordinary words are how the first run put an automated-email complaint
      // on the Settings→Location screen. Naming ONE file requires evidence of
      // a kind, not merely of a quantity:
      //   · a verbatim phrase in the owner's own vocabulary that is itself
      //     distinctive ("new leads", "the kanban"), OR
      //   · a distinctive token — one rare enough to name a thing rather than
      //     describe one — corroborated by at least one other hit from the
      //     description, so a single lucky word is never enough.
      // Everything else can still be a shortlist. It just cannot be an answer.
      corroborated: phraseHit || (peak >= DISTINCTIVE_MIN && hits >= 2),
    })
  }

  scored.sort((a, b) => b.score - a.score || a.id.localeCompare(b.id))
  return scored
}

export function placeFeedbackItem(
  item: { title?: string | null; description?: string | null },
  index: PlacementIndex,
): Placement {
  const scored = rankPlacements(item, index)
  if (scored.length === 0) return { confidence: 'none', candidates: [] }

  const top = scored[0]
  const second = scored[1]

  if (
    top.score >= CONFIDENT_MIN &&
    top.corroborated &&
    (!second || top.score >= second.score * CONFIDENT_MARGIN)
  ) {
    return { confidence: 'confident', candidates: [strip(top)] }
  }

  // Not confident. Is there enough to be worth a shortlist at all?
  if (top.score < POSSIBLE_MIN) return { confidence: 'none', candidates: [] }

  const band = scored
    .filter(c => c.score >= top.score * SHORTLIST_BAND)
    .slice(0, SHORTLIST_MAX)
    .map(strip)
  return { confidence: 'possible', candidates: band }
}

function strip(c: PlacementCandidate & { corroborated?: boolean }): PlacementCandidate {
  const { corroborated, ...rest } = c
  return rest
}

// ─── HOW A PLACEMENT SHOULD BE PRINTED ────────────────────────────────
// Issue 248 step 3. Kevin's verdict on the step-2 brief was "feels busy", and
// the diagnosis was structural: the noise was proportional to how UNCERTAIN the
// matcher was, so the reader paid most attention exactly where the brief knew
// least.
//
// His example is the whole rule. "Nuturing" was given three candidates whose
// evidence was `clients, client` — which does not locate anything, it reports
// that the word "client" appears in many screen descriptions. "Guide" was given
// two whose evidence was `guide`, which is real. That is a description, in plain
// English, of the IDF weight this module already computes: `client` occurs in 19
// of 120 entries (weight 1.79), `guide` in 3 (weight 3.40). So the renderer
// reads `peak` and stops guessing.
//
// THREE PRINTED STATES, and the reasoning for each boundary:
//
//   placed    Rests on at least one word that names something, AND is
//             corroborated — either by a second matched word, or by the
//             runner-up agreeing on the same word. Prints as one file path.
//   weak      Rests only on words common enough to mean nothing on their own.
//             Prints the file path AND the matched words, because this is
//             precisely where a reader wants to judge for themselves.
//   unplaced  Says it cannot place this. Which is true, and useful: it tells
//             Kevin which reports need a question asked rather than a file
//             opened.
//
// WHY "AGREEMENT" IS PART OF IT, AND WHAT IT FIXED. A single matched word can be
// a noun that names a surface or a verb that collided with one, and no weight
// separates them — `notes` (the notes box, right) and `feed` (the activity feed,
// wrong: "leads feed directly into Jobber") are both in exactly one entry and
// therefore both score 4.09. That was reported as an unsolved limit in step 2.
// The shortlist itself turns out to carry the missing signal:
//
//   Guide  → shell.guide (guide) + admin.content (guide)      ← both say `guide`
//   Quo    → home.follow-ups (set) + record.notes (client,feed) ← nothing shared
//
// When two different surfaces are pulled in by the SAME word, that word is doing
// real work. When each candidate arrives on a different word, the shortlist is a
// pile of coincidences. Agreement is what lets "Guide" survive while "Quo" —
// which Kevin flagged by name — correctly falls to unplaced.
export type PlacementRender = 'placed' | 'weak' | 'unplaced'

export function placementRender(p: Placement): PlacementRender {
  if (p.confidence === 'none' || p.candidates.length === 0) return 'unplaced'
  // A single confident placement dominated the whole field 2:1 and was
  // corroborated to get that label; it is not the lucky-single-word case.
  if (p.confidence === 'confident') return 'placed'

  const [top, second] = p.candidates

  // Rule 3 — a lone uncertain candidate is worse than silence. It reads as a
  // placement while resting on one word that nothing else corroborates, which
  // is exactly how "Thumbtack Integration → the notes box (matched: feed)" got
  // printed. It reads as unplaced now, which is what it is.
  if (p.candidates.length === 1) return 'unplaced'

  // Rests only on ordinary words — show it, but show the words with it.
  if (top.peak < DISTINCTIVE_MIN) return 'weak'

  // Distinctive, and corroborated by a second word of its own...
  if (top.matched.length >= 2) return 'placed'
  // ...or by the runner-up arriving on the same word.
  if (second && second.matched.some(m => top.matched.includes(m))) return 'placed'

  return 'unplaced'
}
