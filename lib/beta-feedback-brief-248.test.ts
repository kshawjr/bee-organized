// The daily feedback brief — issue 248 step 2.
//
// What these pin, and why each mattered enough to pin:
//
//   1. THE PREMISE THAT WAS WRONG. The 247 scout judged 25 of 28 open reports
//      unlocatable, measuring TITLES and character counts. The descriptions
//      average 147 characters; the titles are the thin part. So the matcher
//      reads the description first, and there is a test whose fixture has a
//      deliberately useless title and a rich description — it is the assertion
//      that the correction actually took.
//   2. THE HONESTY RULE. A confident wrong pointer is worse than silence,
//      because the reader trusts it and loses a morning in the wrong file. So
//      "cannot place this" is asserted as a real, printed output, and the
//      corroboration rules that stop a confident guess are pinned by the two
//      real-world cases that defeated the first implementation.
//   3. ONE DEFINITION OF OPEN AND STALE. Still issue 233's. The brief regroups
//      for reading order; it must never re-derive what open or stale mean.
//   4. THE HEARTBEAT ALLOWLIST. digest_runs now has two writers. Before the
//      label filter, one feedback-brief row would have made a DEAD webhook
//      digest look alive to system-health, silently disarming the alarm that
//      catches a deployment-pinned cron.
import { describe, it, expect, vi, beforeEach } from 'vitest'
import { readFileSync } from 'node:fs'
import {
  buildPlacementIndex, placeFeedbackItem, tokenize, normalizeText,
  type ScreenMapEntry,
} from '@/lib/feedback-placement'
import { buildFeedbackBrief, mistypeFlag, type BriefItem } from '@/lib/feedback-brief'
import { summarizeFeedbackQueues } from '@/lib/feedback-queues'

const map = JSON.parse(readFileSync('docs/screen-map.json', 'utf8')) as { entries: ScreenMapEntry[] }
const index = buildPlacementIndex(map.entries)

const NOW = new Date('2026-08-15T12:00:00Z').getTime()
const daysAgo = (n: number) => new Date(NOW - n * 86400000).toISOString()

const item = (o: Partial<BriefItem> & { createdDays?: number; touchedDays?: number } = {}): BriefItem => {
  const { createdDays = 3, touchedDays, ...rest } = o
  return {
    id: o.id ?? 'x',
    type: 'bug',
    status: 'submitted',
    title: 'a title',
    description: 'a description',
    submitter: 'Ankur Patel',
    location: 'Palm Beach',
    is_internal: false,
    created_at: daysAgo(createdDays),
    updated_at: daysAgo(touchedDays ?? createdDays),
    ...rest,
  }
}

const build = (items: BriefItem[]) => buildFeedbackBrief({ items, index, now: NOW, appUrl: 'https://hub.test' })

