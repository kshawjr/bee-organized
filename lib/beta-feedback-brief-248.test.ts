// THE HEARTBEAT ALLOWLIST — digest_runs now has two writers.
const svc = vi.hoisted(() => ({ rows: [] as any[], captured: [] as any[], filters: [] as any[] }))
vi.mock('@/lib/supabase-service', () => ({
  supabaseService: {
    from() {
      const b: any = {}
      b.select = () => b
      b.in = (col: string, vals: any[]) => { svc.filters.push([col, vals]); return b }
      b.order = () => b
      b.limit = () => Promise.resolve({
        data: svc.rows.filter(r =>
          svc.filters.every(([c, v]) => v.includes(r[c])),
        ),
        error: null,
      })
      b.insert = (rows: any) => { svc.captured.push(rows); return Promise.resolve({ error: null }) }
      return b
    },
  },
}))

describe('digest_runs liveness — the feedback brief must not answer for the webhook digest', () => {
  beforeEach(() => { svc.rows = []; svc.captured = []; svc.filters = [] })

  it('THE DEFECT: a fresh feedback-brief row must not make a dead webhook digest look alive', async () => {
    const { fetchLatestDigestRun } = await import('@/lib/digest-runs')
    svc.rows = [
      { ran_at: '2026-08-01T10:00:00Z', window_label: 'last 24h' },   // webhook digest, 14 days stale
      { ran_at: '2026-08-15T11:00:00Z', window_label: 'feedback brief' }, // today, different cron
    ]
    const { run } = await fetchLatestDigestRun()
    expect(run?.window_label).toBe('last 24h')
    expect(run?.ran_at).toBe('2026-08-01T10:00:00Z')
  })

  it('the historical "last 3h" cadence still counts as the webhook digest', async () => {
    const { fetchLatestDigestRun } = await import('@/lib/digest-runs')
    svc.rows = [{ ran_at: '2026-07-30T10:00:00Z', window_label: 'last 3h' }]
    const { run } = await fetchLatestDigestRun()
    expect(run?.window_label).toBe('last 3h')
  })

  it('the brief writes its own label, and records even a suppressed run', async () => {
    const { recordFeedbackBriefRun, FEEDBACK_BRIEF_LABEL } = await import('@/lib/digest-runs')
    await recordFeedbackBriefRun({ suppressed: true, text: '' }, { ok: false })
    expect(svc.captured[0].window_label).toBe(FEEDBACK_BRIEF_LABEL)
    expect(svc.captured[0].suppressed).toBe(true)
    expect(svc.captured[0].message_text).toBeNull()
  })

  it('a posted run stores the message text, so the brief is auditable after the fact', async () => {
    const { recordFeedbackBriefRun } = await import('@/lib/digest-runs')
    await recordFeedbackBriefRun({ suppressed: false, text: 'the brief' }, { ok: true })
    expect(svc.captured[0].posted).toBe(true)
    expect(svc.captured[0].message_text).toBe('the brief')
  })
})

