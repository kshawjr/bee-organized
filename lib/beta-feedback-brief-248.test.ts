describe('suppression — a quiet day says nothing', () => {
  it('suppresses when nothing is new and nothing newly went stale', () => {
    const brief = build([
      item({ id: 'a', status: 'submitted', createdDays: 5 }),
      item({ id: 'b', status: 'under_review', createdDays: 40, touchedDays: 30 }),
    ])
    expect(brief.suppressed).toBe(true)
    expect(brief.text).toBe('')
  })

  it('does NOT suppress when something arrived today', () => {
    const brief = build([item({ id: 'a', createdDays: 0 })])
    expect(brief.suppressed).toBe(false)
    expect(brief.newCount).toBe(1)
  })

  it('does NOT suppress when something newly went quiet — the day it crosses 14', () => {
    // Untouched for exactly 14 days: stale now, not stale a day ago.
    const brief = build([
      item({ id: 'b', status: 'under_review', createdDays: 40, touchedDays: 14 }),
    ])
    expect(brief.newlyStaleCount).toBe(1)
    expect(brief.suppressed).toBe(false)
    expect(brief.text).toContain('JUST WENT QUIET')
  })

  it('an item quiet for a long time does not re-trigger every day', () => {
    const brief = build([
      item({ id: 'b', status: 'under_review', createdDays: 60, touchedDays: 45 }),
    ])
    expect(brief.newlyStaleCount).toBe(0)
    expect(brief.suppressed).toBe(true)
  })

  it('an empty queue is a quiet day, not a crash', () => {
    const brief = build([])
    expect(brief.suppressed).toBe(true)
    expect(brief.openCount).toBe(0)
  })
})

