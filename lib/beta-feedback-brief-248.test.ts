describe('grouping and order', () => {
  const items = [
    item({ id: 'bug-young', type: 'bug', createdDays: 2, title: 'young bug' }),
    item({ id: 'bug-old', type: 'bug', createdDays: 30, title: 'old bug' }),
    item({ id: 'feat', type: 'feature', createdDays: 9, title: 'a feature' }),
    item({ id: 'dec', type: 'decision', is_internal: true, createdDays: 5, title: 'a decision' }),
    item({ id: 'haz', type: 'hazard', is_internal: true, createdDays: 4, title: 'a hazard' }),
    item({ id: 'new', type: 'bug', createdDays: 0, title: 'brand new' }),
  ]

  it('bugs lead, then features, then decisions, then hazards', () => {
    const brief = build(items)
    const t = brief.text
    expect(t.indexOf('*BUGS*')).toBeGreaterThan(-1)
    expect(t.indexOf('*BUGS*')).toBeLessThan(t.indexOf('*FEATURES*'))
    expect(t.indexOf('*FEATURES*')).toBeLessThan(t.indexOf('*DECISIONS*'))
    expect(t.indexOf('*DECISIONS*')).toBeLessThan(t.indexOf('*HAZARDS*'))
  })

  it('OLDEST FIRST inside each group — the quiet three-week bug is not buried', () => {
    const brief = build(items)
    const bugs = brief.groups.find(g => g.type === 'bug')!.lines.map(l => l.ageDays)
    expect(bugs).toEqual([30, 2, 0])
  })

  it('age prints as "19 days", never as a date', () => {
    const brief = build([
      item({ id: 'aged', createdDays: 19, title: 'aged' }),
      item({ id: 'fresh', createdDays: 0, title: 'fresh' }), // else the day is quiet and nothing prints
    ])
    expect(brief.text).toContain('19 days')
    expect(brief.text).not.toMatch(/\d{4}-\d{2}-\d{2}/)
  })

  it('an unrecognised type is still shown rather than silently dropped', () => {
    const brief = build([item({ id: 'weird', type: 'mystery', createdDays: 0, title: 'odd one' })])
    expect(brief.text).toContain('*OTHER*')
    expect(brief.text).toContain('odd one')
  })
})

