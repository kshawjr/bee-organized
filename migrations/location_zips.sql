-- WHAT. One row per (zip, location) a franchise covers. POST /api/leads/intake
-- reads it when a lead arrives with NO location (the website's global form,
-- zip only): exactly one row for the zip → that location; zero rows, or two or
-- more (a CONFLICT) → loc_other, Leslie's queue. lib/zip-routing.ts holds the
-- rule. Corporate edits the list in Admin → Zip codes
-- (app/api/admin/location-zips), so a conflict is settled by deleting the row
-- that should lose — no migration needed.
--
-- A CONFLICT IS DATA, NOT AN ERROR. The same zip under two locations is kept
-- as two rows on purpose: Kevin's ruling (30 Sep 2026) is that the 11 Denver
-- zips claimed twice are UNKNOWN for now and go to Leslie. Nothing here picks
-- a winner. UNIQUE (zip, location_uuid) only stops the same pair twice.
--
-- SOURCE. Territory Zip Codes_2026.xlsx, sheet "Zip Codes" (Kevin's Drive,
-- 30 Sep 2026): 54 columns, 1,608 entries, 1,580 unique zips.
--   · 17 rows repeat a zip inside the SAME column — collapsed by DISTINCT.
--   · 133 zips lost their leading zero in the spreadsheet (New England, NJ:
--     2801 for 02801) — every zip below is re-padded to five digits.
--   · The sheet names are NOT Bee Hub's names. The mapping block below is the
--     same list as lib/zip-territory-sheet.ts (a test pins the two together).
--     "Central AR" and "South Valley" have no Bee Hub location: mapped to NULL,
--     NOT loaded, so their zips route to loc_other until Kevin says otherwise.
--
-- JOINED ON NAME, NOT SLUG. The sheet has names; the brief has names. Block 2
-- REFUSES TO LOAD ANYTHING if any mapped name does not match exactly one
-- location (case- and edge-space-insensitive), or matches loc_other. The error
-- lists every bad name. A silent partial import is the failure this avoids.
--
-- RUN AS TWO STATEMENTS (the Supabase SQL editor is fine with this):
--   Block 1 — the table. Idempotent.
--   Block 2 — ONE DO block: check names, load, check the count. It is atomic:
--             any RAISE rolls the whole load back. Re-running is safe
--             (ON CONFLICT DO NOTHING); a pair corporate DELETED since will be
--             re-added by a re-run, so do not re-run after the list is in use.
--
-- NO POLICIES. RLS is on with no policy: anon/authenticated clients can read
-- nothing. The service-role client (intake, the admin API) bypasses RLS; the
-- admin route gates on super_admin/admin before touching it.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Block 1: the table ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.location_zips (
  id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  zip            text        NOT NULL CHECK (zip ~ '^[0-9]{5}$'),
  location_uuid  uuid        NOT NULL REFERENCES public.locations(id) ON DELETE CASCADE,
  created_at     timestamptz NOT NULL DEFAULT now(),
  -- hub_users.id of whoever added/moved it in the admin screen; NULL = this load.
  updated_by     uuid        NULL,
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT location_zips_zip_location_key UNIQUE (zip, location_uuid)
);

CREATE INDEX IF NOT EXISTS location_zips_zip_idx ON public.location_zips (zip);
CREATE INDEX IF NOT EXISTS location_zips_location_idx ON public.location_zips (location_uuid);

